import fs from 'fs'
import path from 'path'
import {fileURLToPath} from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const formatDateRu = date => {
  const dd = String(date.getDate()).padStart(2, '0')
  const mm = String(date.getMonth() + 1).padStart(2, '0')
  const yyyy = date.getFullYear()
  const hh = String(date.getHours()).padStart(2, '0')
  const min = String(date.getMinutes()).padStart(2, '0')
  const ss = String(date.getSeconds()).padStart(2, '0')
  
  return `${dd}.${mm}.${yyyy} ${hh}:${min}:${ss}`
}

const getPackageJson = () => {
  const packageJsonPath = path.resolve(__dirname, '../../package.json')
  return JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'))
}

const generateBuildMeta = () => {
  const pkg = getPackageJson()
  const buildDate = formatDateRu(new Date())
  
  const buildMetaFile = path.resolve(__dirname, '../../src/game/generatedAssets/buildMeta.js')
  
  fs.writeFileSync(
    buildMetaFile,
    `// AUTOGENERATED FILE. DO NOT EDIT
export const BUILD_VERSION = '${buildDate}'
export const PACKAGE_VERSION = '${pkg.version}'
export const CACHE_VERSION = '${pkg.version}-${Date.now()}'
export const GAME_NAME = '${pkg.name}'
`
  )
}

export {generateBuildMeta}
